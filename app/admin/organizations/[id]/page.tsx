/* =========================================================
   DATE HELPERS
   ========================================================= */

/**
 * Adds months without allowing dates such as Jan 31
 * to unexpectedly jump two months forward.
 */
function addMonthsSafe(
  date: Date,
  months: number
) {
  const result = new Date(date);

  const originalDay =
    result.getDate();

  result.setDate(1);

  result.setMonth(
    result.getMonth() + months
  );

  const lastDayOfMonth =
    new Date(
      result.getFullYear(),
      result.getMonth() + 1,
      0
    ).getDate();

  result.setDate(
    Math.min(
      originalDay,
      lastDayOfMonth
    )
  );

  return result;
}

function calculateExpiry(
  baseDate: Date,
  duration: ParsedDuration
) {
  const result = new Date(baseDate);

  switch (duration.unit) {
    case "minutes":
      result.setMinutes(
        result.getMinutes() +
          duration.value
      );
      break;

    case "hours":
      result.setHours(
        result.getHours() +
          duration.value
      );
      break;

    case "days":
      result.setDate(
        result.getDate() +
          duration.value
      );
      break;

    case "months":
      return addMonthsSafe(
        result,
        duration.value
      );
  }

  return result;
}

/* =========================================================
   SERVER ACTION
   ========================================================= */

async function changeSubscription(
  formData: FormData
) {
  "use server";

  /*
   * IMPORTANT:
   * Never trust the page/middleware alone.
   * Server actions must authorize themselves.
   */
  await requireSuperAdmin();

  const orgId =
    getString(formData, "orgId");

  const planValue =
    getString(formData, "plan");

  const durationValue =
    getString(formData, "duration");

  const startFromNow =
    getBoolean(
      formData,
      "startFromNow"
    );

  if (!orgId) {
    redirect(
      "/admin/organizations?subscriptionError=Organization%20ID%20is%20required"
    );
  }

  /*
   * Validate plan against Prisma enum.
   */
  if (
    !Object.values(
      SubscriptionPlan
    ).includes(
      planValue as SubscriptionPlan
    )
  ) {
    redirect(
      `/admin/organizations/${encodeURIComponent(
        orgId
      )}?subscriptionError=Invalid%20subscription%20plan`
    );
  }

  const plan =
    planValue as SubscriptionPlan;

  /*
   * Parse duration before touching the database.
   */
  let duration: ParsedDuration;

  try {
    duration =
      parseDuration(
        durationValue
      );
  } catch (error) {
    console.error(
      "Subscription duration error:",
      error
    );

    redirect(
      `/admin/organizations/${encodeURIComponent(
        orgId
      )}?subscriptionError=${encodeURIComponent(
        error instanceof Error
          ? error.message
          : "Invalid subscription duration"
      )}`
    );
  }

  /*
   * Load organization + actual plan.
   *
   * The Plan table is now the source of truth for:
   * price
   * user limit
   * storage limit
   * AI credits
   */
  const [organization, planRecord] =
    await Promise.all([
      prisma.organization.findUnique({
        where: {
          id: orgId,
        },
        select: {
          id: true,
          name: true,
          active: true,
          plan: true,
          subscriptionEndsAt: true,
        },
      }),

      prisma.plan.findUnique({
        where: {
          code: plan,
        },
      }),
    ]);

  if (!organization) {
    redirect(
      `/admin/organizations/${encodeURIComponent(
        orgId
      )}?subscriptionError=Organization%20not%20found`
    );
  }

  if (!planRecord) {
    redirect(
      `/admin/organizations/${encodeURIComponent(
        orgId
      )}?subscriptionError=Selected%20plan%20was%20not%20found`
    );
  }

  /*
   * Current time.
   */
  const now = new Date();

  /*
   * If admin explicitly selects "Start from current time",
   * ignore the current expiry.
   *
   * Otherwise:
   * - active subscription -> extend from current expiry
   * - expired/missing -> start from now
   */
  let baseDate: Date;

  if (startFromNow) {
    baseDate = new Date(now);
  } else if (
    organization.subscriptionEndsAt &&
    organization.subscriptionEndsAt > now
  ) {
    baseDate =
      new Date(
        organization.subscriptionEndsAt
      );
  } else {
    baseDate = new Date(now);
  }

  /*
   * Calculate new expiry.
   */
  const expiresAt =
    calculateExpiry(
      baseDate,
      duration
    );

  /*
   * Defensive validation.
   */
  if (
    Number.isNaN(
      expiresAt.getTime()
    ) ||
    expiresAt <= baseDate
  ) {
    redirect(
      `/admin/organizations/${encodeURIComponent(
        orgId
      )}?subscriptionError=Could%20not%20calculate%20subscription%20expiry`
    );
  }

  console.log(
    "[ADMIN SUBSCRIPTION CHANGE]",
    {
      orgId,
      plan,
      duration: durationValue,
      durationParsed: duration,
      startFromNow,
      baseDate,
      expiresAt,
    }
  );

  /*
   * IMPORTANT:
   *
   * Subscription + Organization are updated
   * atomically.
   */
  try {
    await prisma.$transaction(
      async (tx) => {
        /*
         * Create or update the real subscription.
         */
        await tx.subscription.upsert({
          where: {
            orgId,
          },

          create: {
            orgId,

            provider: "admin",

            externalId: null,

            customerId: null,

            plan,

            status:
              SubscriptionStatus.active,

            billingCycle: "monthly",

            amount:
              new Prisma.Decimal(
                planRecord.price
              ),

            currency:
              planRecord.currency ||
              "USD",

            renewAt: expiresAt,

            nextInvoiceDate:
              expiresAt,

            trialStart: null,

            trialEnd: null,

            interval: "month",

            cancelAtPeriodEnd:
              false,

            userLimit:
              planRecord.userLimit,

            storageLimit:
              planRecord.storageLimit,

            aiCredits:
              planRecord.aiCredits,
          },

          update: {
            plan,

            status:
              SubscriptionStatus.active,

            amount:
              new Prisma.Decimal(
                planRecord.price
              ),

            currency:
              planRecord.currency ||
              "USD",

            renewAt: expiresAt,

            nextInvoiceDate:
              expiresAt,

            billingCycle:
              "monthly",

            interval:
              "month",

            cancelAtPeriodEnd:
              false,

            userLimit:
              planRecord.userLimit,

            storageLimit:
              planRecord.storageLimit,

            aiCredits:
              planRecord.aiCredits,
          },
        });

        /*
         * Keep Organization synchronized.
         */
        await tx.organization.update({
          where: {
            id: orgId,
          },

          data: {
            plan,

            active: true,

            usersLimit:
              planRecord.userLimit,

            subscriptionEndsAt:
              expiresAt,
          },
        });
      }
    );
  } catch (error) {
    console.error(
      "[ADMIN SUBSCRIPTION CHANGE FAILED]",
      error
    );

    const message =
      error instanceof Error
        ? error.message
        : "Subscription update failed";

    redirect(
      `/admin/organizations/${encodeURIComponent(
        orgId
      )}?subscriptionError=${encodeURIComponent(
        message
      )}`
    );
  }

  /*
   * Refresh all affected admin pages.
   */
  revalidatePath(
    `/admin/organizations/${orgId}`
  );

  revalidatePath(
    `/admin/organizations/${orgId}/users`
  );

  revalidatePath(
    `/admin/organizations/${orgId}/billing`
  );

  revalidatePath(
    `/admin/organizations`
  );

  revalidatePath(
    "/admin/subscriptions"
  );

  revalidatePath(
    "/admin/dashboard"
  );

  /*
   * Redirect instead of returning a raw server-action
   * response. This prevents the generic "page couldn't load"
   * experience after a successful update.
   */
  redirect(
    `/admin/organizations/${encodeURIComponent(
      orgId
    )}?subscription=success`
  );
}

/* =========================================================
   FORMATTERS
   ========================================================= */

function formatPlan(
  plan: SubscriptionPlan | null | undefined
) {
  if (!plan) {
    return "—";
  }

  switch (plan) {
    case SubscriptionPlan.starter:
      return "Starter";

    case SubscriptionPlan.professional:
      return "Professional";

    case SubscriptionPlan.enterprise:
      return "Enterprise";

    default:
      return String(plan);
  }
}

function formatMoney(
  amount:
    | Prisma.Decimal
    | number
    | null
    | undefined
) {
  if (
    amount === null ||
    amount === undefined
  ) {
    return "$0.00";
  }

  return new Intl.NumberFormat(
    "en-US",
    {
      style: "currency",
      currency: "USD",
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    }
  ).format(Number(amount));
}

function formatDate(
  date:
    | Date
    | null
    | undefined
) {
  if (!date) {
    return "No subscription";
  }

  return new Intl.DateTimeFormat(
    "en-US",
    {
      year: "numeric",
      month: "short",
      day: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    }
  ).format(date);
}

function formatLimit(
  value:
    | number
    | null
    | undefined
) {
  if (
    value === null ||
    value === undefined
  ) {
    return "—";
  }

  /*
   * Your current seed/database uses unlimited
   * plans. If represented by -1, display Unlimited.
   */
  if (value < 0) {
    return "Unlimited";
  }

  return value.toLocaleString(
    "en-US"
  );
}

