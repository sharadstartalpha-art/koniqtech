/* =========================================================
   PLATFORM AUTHORIZATION
   ========================================================= */

async function requireSuperAdmin() {
  const session = await auth();

  if (!session?.user) {
    redirect("/login");
  }

  const user = session.user as {
    role?: unknown;
  };

  const role = String(user.role ?? "")
    .trim()
    .toLowerCase();

  if (role !== "super_admin") {
    redirect("/admin/dashboard");
  }

  return session;
}

/* =========================================================
   FORM HELPERS
   ========================================================= */

function getString(
  formData: FormData,
  key: string
) {
  return String(
    formData.get(key) ?? ""
  ).trim();
}

function getBoolean(
  formData: FormData,
  key: string
) {
  const value = formData.get(key);

  return (
    value === "true" ||
    value === "1" ||
    value === "on"
  );
}

